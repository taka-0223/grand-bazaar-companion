#!/usr/bin/env node
// Keep offline Record Book data synchronized with the audited canonical catalogs.
import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {projectRecordMaster} from '../lib/record-master-projection.mjs';

const read=path=>JSON.parse(readFileSync(path,'utf8'));
const catalog=projectRecordMaster(
  read('data/board-master.full.v1.json'),
  read('data/tool-upgrades.v1.json'),
  read('data/bazaar-facilities.v1.json'),
  read('data/bazaar-shops.v1.json')
);
const path='record-master.js';
const output='// Generated by tools/build-record-master.mjs; do not edit manually.\n'+
  'const RECORD_MASTER='+JSON.stringify(catalog).replace(/</g,'\\u003c')+';\n';
if(process.argv.includes('--write'))writeFileSync(path,output);
else if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8'),output,
  'record-master.js is stale; run node tools/build-record-master.mjs --write');
else throw new Error('Use --write or --check');
console.log(JSON.stringify({mode:process.argv.includes('--write')?'write':'check',
  tools:catalog.tools.length,upgrades:catalog.upgrades.length,
  facilities:catalog.facilities.length,bytes:Buffer.byteLength(output)}));
